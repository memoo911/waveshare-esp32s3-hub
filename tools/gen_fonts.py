#!/usr/bin/env python3
"""Generate anti-aliased 4-bit fonts for the weather screen.

Rasterizes the Inter typeface (SIL Open Font License) with Pillow and writes
src/Fonts.h. Each glyph is stored as 4-bit alpha, two pixels per byte, rows
padded to whole bytes. Includes ASCII plus the Croatian letters, so text like
"Četvrtak" renders with proper diacritics.

    python3 tools/gen_fonts.py [--fonts-dir /usr/share/fonts/opentype/inter]
"""

import argparse
import os

from PIL import ImageFont

ASCII = "".join(chr(c) for c in range(32, 127))
CROATIAN = "čćžšđČĆŽŠĐ"
EXTRA = "°·↑↓…"
TEXT = ASCII + CROATIAN + EXTRA

# (C name, font file, pixel size, characters)
FONTS = [
    ("kFontClock", "InterDisplay-Light.otf", 112, "0123456789:-"),
    ("kFontTemp", "InterDisplay-Light.otf", 84, "0123456789-.° %:+"),
    ("kFontTitle", "Inter-SemiBold.otf", 26, TEXT),
    ("kFontBody", "Inter-Regular.otf", 21, TEXT),
    ("kFontSmall", "Inter-Medium.otf", 17, TEXT),
]


def render_font(name, path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    bitmap = bytearray()
    for ch in sorted(set(chars), key=ord):
        mask, offset = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        advance = int(round(font.getlength(ch)))
        start = len(bitmap)
        row_bytes = (w + 1) // 2
        for y in range(h):
            row = bytearray(row_bytes)
            for x in range(w):
                a = mask.getpixel((x, y)) >> 4
                if x % 2 == 0:
                    row[x // 2] |= a << 4
                else:
                    row[x // 2] |= a
            bitmap += row
        glyphs.append((ord(ch), w, h, offset[0], offset[1], advance, start, ch))

    out = []
    out.append(f"// {name}: {os.path.basename(path)} {size}px, {len(glyphs)} glyphs, "
               f"{len(bitmap)} bytes")
    out.append(f"static const uint8_t {name}Bits[] = {{")
    for i in range(0, len(bitmap), 24):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const Glyph {name}Glyphs[] = {{")
    for code, w, h, xo, yo, adv, start, ch in glyphs:
        label = ch if ch not in "\\" else "backslash"
        out.append(f"    {{0x{code:04X}, {w}, {h}, {xo}, {yo}, {adv}, {start}}}, // {label}")
    out.append("};")
    out.append(f"static const Font {name} = {{{name}Glyphs, {len(glyphs)}, {name}Bits, "
               f"{ascent}, {descent}}};")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--fonts-dir", default="/usr/share/fonts/opentype/inter")
    parser.add_argument("--out", default=os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "src", "Fonts.h"))
    args = parser.parse_args()

    parts = [
        "#pragma once",
        "",
        "// Generated by tools/gen_fonts.py from the Inter typeface",
        "// (https://rsms.me/inter, SIL Open Font License 1.1). Do not edit.",
        "",
        "#include \"Render.h\"",
        "",
    ]
    for name, file, size, chars in FONTS:
        parts.append(render_font(name, os.path.join(args.fonts_dir, file), size, chars))
        parts.append("")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
